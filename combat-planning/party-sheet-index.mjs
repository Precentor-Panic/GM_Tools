/**
 * Party-sheet projection — the Run view's party rail (2026-10-06).
 *
 * A PURE, read-through projection of the Foundry index's PC actors into the
 * numbers a GM needs at the table: passive Perception first (the rail's whole
 * reason to exist), then every skill modifier/passive, the six saves, and the
 * ability scores. No fs, no network; takes an already-parsed index object.
 *
 * WHY THIS IS A PROJECTION AND NOT A STORE. Nothing here is persisted, and
 * that is deliberate. `combat-planning/party-roster-store.mjs` already tried
 * to hold a PC's passive in a `passive` scalar, and the monument to that
 * approach is `passive: null` on every PC in every world -- derived numbers
 * copied into a second store rot the moment somebody levels up. The index is
 * regenerated by a Foundry-side reindex and is the single source of truth, so
 * this module reads through to it and the caller surfaces the age honestly.
 * Consequence worth stating for the next reader: **this path writes nothing**,
 * so the no-silent-auto-write invariant is untouched -- there is no
 * status:'proposed' step to skip here, because there is no write.
 *
 * The roster store keeps owning what it is actually good at: the GM's own
 * CURATED data (name, conditions, objectives, foundryActorRef). The optional
 * roster join below is that, and only that.
 *
 * !! DO NOT "DRY THIS UP" INTO classifyActor !!
 * `foundry-actor-mapper.mjs`'s `classifyActor` falls back to
 * `actor.type === "character"` when no user claims an actor -- a documented,
 * correct heuristic for ITS job (deciding pc-vs-monster during a pull). It is
 * the wrong rule here: every player in this campaign also keeps a pack-MULE
 * actor typed `character`, so in the real aureus world that fallback yields 14
 * "PCs" where there are 7 seats. This module uses the strict seat rule --
 * `index.users[].characterUuid` ONLY -- and the mule test in
 * test/combat-planning/party-sheet-index.test.mjs pins exactly that
 * divergence. If you replace this with classifyActor, the mules come back.
 */

/** Wire-format version, echoed in the payload. Bump on a breaking shape change. */
export const PARTY_SHEETS_VERSION = 1;

/**
 * The 18 dnd5e skill keys in a fixed order. Fixed so the projection is
 * deterministic (tests assert order) and so a rail row can index positionally.
 */
export const SKILL_KEYS = Object.freeze([
  "acr", "ani", "arc", "ath", "dec", "his", "ins", "inv", "itm",
  "med", "nat", "prc", "prf", "rel", "slt", "ste", "sur", "per"
]);

/** Ability keys, PHB order. */
export const ABILITY_KEYS = Object.freeze(["str", "dex", "con", "int", "wis", "cha"]);

/** Human labels, for a caller that wants them without a second table. */
export const SKILL_LABELS = Object.freeze({
  acr: "Acrobatics", ani: "Animal Handling", arc: "Arcana", ath: "Athletics",
  dec: "Deception", his: "History", ins: "Insight", inv: "Investigation",
  itm: "Intimidation", med: "Medicine", nat: "Nature", prc: "Perception",
  prf: "Performance", rel: "Religion", slt: "Sleight of Hand", ste: "Stealth",
  sur: "Survival", per: "Persuasion"
});

/** A number, or null. Never 0-as-missing — `mapActorToBestiary`'s own honesty
 * rule for absent hp/ac, applied here to every number. */
function num(v) {
  return typeof v === "number" && Number.isFinite(v) ? v : null;
}

/**
 * dnd5e 5.x gives `abilities.<k>.save` as `{roll:{…}, value:N}`, while older
 * data (and the bridge contract's own §1.1 text) says a bare number. READ THE
 * OBJECT -- passing it through verbatim is precisely the bug that put
 * `{roll,value}` objects into `combatRelevant.saveDCs`, where the zod schema
 * says `z.record(z.string(), z.number())` and `library-view.js` has to patch
 * over it at render time. Do not repeat it.
 */
function saveValue(raw) {
  if (raw && typeof raw === "object") return num(raw.value);
  return num(raw);
}

/**
 * The proficiency bonus is NOT in the index (verified: no `attributes.prof` on
 * any of the 35 real actors), so derive it from level by the 5e table. Null
 * when there is no usable level rather than guessing +2.
 */
export function proficiencyBonusForLevel(level) {
  const l = num(level);
  if (l === null || l < 1) return null;
  return 2 + Math.floor((Math.min(l, 20) - 1) / 4);
}

/**
 * A rail-sized label: the part of the name before the first "&", " and " or
 * comma, so "Flint CinderLeaf & Comrade Kindle" reads as "Flint CinderLeaf" in
 * a 232px column. The full name still rides along for a title attribute.
 */
export function compactLabel(name) {
  const s = String(name ?? "").trim();
  if (!s) return "";
  const cut = s.split(/\s+&\s+|\s+and\s+|,/)[0].trim();
  return cut || s;
}

/**
 * "This seat has no sheet filled in." No class item, no usable level, and no
 * skill proficiencies at all. In the real world this is exactly the one player
 * who is not currently playing (their actor still exists, deliberately -- see
 * the campaign's own never-delete-a-player-actor rule).
 *
 * Russell's call, 2026-10-06: such a seat is EXCLUDED from the rail rather than
 * dimmed, because a character nobody is playing is noise at the table. The
 * caller gets them back under `excluded` so the omission is inspectable and
 * never silent.
 */
export function isEmptySheet(actor) {
  const system = actor?.system ?? {};
  const items = Array.isArray(actor?.items) ? actor.items : [];
  const hasClass = items.some((it) => it?.type === "class");
  const level = num(system.level);
  const skills = system.skills && typeof system.skills === "object" ? system.skills : {};
  const anyProficiency = Object.values(skills).some((s) => (num(s?.proficient) ?? 0) > 0);
  return !hasClass && !level && !anyProficiency;
}

/**
 * One index actor + its seat → one rail row. Every accessor optional-chained:
 * the bridge contract's "no mapper may assume any system.* field is present"
 * rule applies here as much as to its siblings.
 *
 * @param {object} actor  an index actor record
 * @param {{userId?:string, userName?:string}} [seat]
 * @returns {object} one party-sheet row
 */
export function mapActorToPartySheet(actor, seat = {}) {
  const system = actor?.system ?? {};
  const rawSkills = system.skills && typeof system.skills === "object" ? system.skills : {};
  const rawAbilities = system.abilities && typeof system.abilities === "object" ? system.abilities : {};
  const rawSaves = system.saves && typeof system.saves === "object" ? system.saves : {};
  const items = Array.isArray(actor?.items) ? actor.items : [];

  const cls = items.find((it) => it?.type === "class")?.name ?? null;
  const name = actor?.name ?? null;

  // All 18 keys always present, in SKILL_KEYS order; a skill the actor's sheet
  // does not carry comes through as nulls, never zeros.
  const skills = SKILL_KEYS.map((key) => {
    const s = rawSkills[key] ?? {};
    return {
      key,
      label: SKILL_LABELS[key],
      mod: num(s.value),
      passive: num(s.passive),
      // dnd5e's raw 0 | 0.5 | 1 | 2 — kept raw so the UI can render half
      // proficiency and expertise distinctly rather than flattening to a bool.
      prof: num(s.proficient) ?? 0
    };
  });

  const passiveFor = (key) => num(rawSkills[key]?.passive);

  return {
    actorUuid: actor?.uuid ?? null,
    userId: seat.userId ?? null,
    userName: seat.userName ?? null,
    name,
    label: compactLabel(name),
    cls,
    level: num(system.level),
    profBonus: proficiencyBonusForLevel(system.level),
    ac: num(system.ac),
    // HP MAX ONLY is displayed by the rail (Russell, 2026-10-06: in-session hit
    // points stay in Foundry). `hpValue` rides along for a future caller but
    // the rail must not show it -- the index can be days old, and this app has
    // been burned by stale current-HP before.
    hpMax: num(system.hp?.max),
    hpValue: num(system.hp?.value),
    passive: { prc: passiveFor("prc"), ins: passiveFor("ins"), inv: passiveFor("inv") },
    skills,
    saves: ABILITY_KEYS.map((key) => ({ key, mod: saveValue(rawAbilities[key]?.save ?? rawSaves[key]) })),
    abilities: ABILITY_KEYS.map((key) => ({ key, score: num(rawAbilities[key]?.value), mod: num(rawAbilities[key]?.mod) })),
    // Filled by the optional roster join — the GM's curated layer.
    rosterMemberId: null,
    conditions: null
  };
}

/**
 * Every actor uuid that belongs to a PLAYER, as a Set — the guard set for
 * "never write to a player character" (push round, 2026-10-07).
 *
 * Deliberately BROADER than partySheetsFromIndex's own seat list, and the
 * difference is the whole point: that function drops a claimed actor with an
 * empty sheet, because an empty row in the rail is noise. A safety guard must
 * do the opposite — an unfinished PC is still a PC, and so is one whose
 * roster row is the only record of it. Union of both sources, never the
 * intersection.
 *
 * Discarded roster rows are excluded: the real aureus world carries a
 * discarded duplicate of one PC, and treating a dead row as protected would
 * block a legitimate push to whatever reused that uuid.
 *
 * Still NOT `classifyActor` — see the header's do-not-DRY note. Its
 * `type === "character"` fallback counts every player's pack mule, which
 * would over-block rather than under-block, but on a guard that silently
 * refuses writes "too many" is its own kind of wrong.
 *
 * @param {object|null} index  a parsed world-fabric-foundry-index.json
 * @param {object[]} [rosterMembers]  listPartyMembers(world) output
 * @returns {Set<string>}
 */
export function playerCharacterUuids(index, rosterMembers = []) {
  const out = new Set();
  for (const u of Array.isArray(index?.users) ? index.users : []) {
    if (u?.characterUuid != null) out.add(String(u.characterUuid));
  }
  for (const m of Array.isArray(rosterMembers) ? rosterMembers : []) {
    if (m?.status === "discarded") continue;
    if (m?.foundryActorRef != null) out.add(String(m.foundryActorRef));
  }
  return out;
}

/**
 * The whole projection.
 *
 * Seats come from `index.users[].characterUuid` ONLY (see the header's
 * do-not-DRY note). Rows are sorted by passive Perception descending, because
 * the rail's job is "who notices" and the likeliest answer belongs at the top;
 * a row with no passive sorts last, then by name for determinism.
 *
 * @param {object|null} index  a parsed world-fabric-foundry-index.json
 * @param {object} [opts]
 * @param {object[]} [opts.rosterMembers]  listPartyMembers(world) output, for the curated join
 * @returns {{version:number, exportedAt:string|null, sheets:object[], excluded:object[]}}
 */
export function partySheetsFromIndex(index, opts = {}) {
  const actors = Array.isArray(index?.actors) ? index.actors : [];
  const users = Array.isArray(index?.users) ? index.users : [];
  const rosterMembers = Array.isArray(opts.rosterMembers) ? opts.rosterMembers : [];

  const byUuid = new Map();
  for (const a of actors) if (a?.uuid != null) byUuid.set(a.uuid, a);

  // A discarded roster row must never win the join — the real world carries a
  // discarded duplicate of one PC.
  const rosterByRef = new Map();
  for (const m of rosterMembers) {
    if (m?.status === "discarded") continue;
    if (m?.foundryActorRef != null && !rosterByRef.has(m.foundryActorRef)) rosterByRef.set(m.foundryActorRef, m);
  }

  const sheets = [];
  const excluded = [];
  const seen = new Set();

  for (const u of users) {
    const uuid = u?.characterUuid;
    if (uuid == null || seen.has(uuid)) continue;
    seen.add(uuid);
    const actor = byUuid.get(uuid);
    if (!actor) continue; // a claimed actor that is no longer in the world
    if (isEmptySheet(actor)) {
      excluded.push({ actorUuid: uuid, name: actor?.name ?? null, reason: "no sheet filled in" });
      continue;
    }
    const row = mapActorToPartySheet(actor, { userId: u?.id ?? u?.userId ?? null, userName: u?.name ?? null });
    const rosterRow = rosterByRef.get(uuid);
    if (rosterRow) {
      row.rosterMemberId = rosterRow.id ?? null;
      row.conditions = rosterRow.conditions ?? null;
    }
    sheets.push(row);
  }

  sheets.sort((a, b) => {
    const pa = a.passive.prc, pb = b.passive.prc;
    if (pa === null && pb !== null) return 1;
    if (pb === null && pa !== null) return -1;
    if (pa !== pb) return (pb ?? 0) - (pa ?? 0);
    return String(a.name ?? "").localeCompare(String(b.name ?? ""));
  });

  return {
    version: PARTY_SHEETS_VERSION,
    exportedAt: index?.exportedAt ?? null,
    sheets,
    excluded
  };
}
